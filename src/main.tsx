/** Renderer entry point: pick the platform, load preferences, start the app. */
import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { getPlatform } from './platform/index.ts';
import { Preferences } from './app/preferences.ts';
import { AppController } from './app/app-controller.ts';
import { AppContext } from './hooks/use-app.ts';
import { App } from './App.tsx';
import './styles/globals.css';

const platform = getPlatform();
const prefs = await Preferences.load(platform);
const app = new AppController(platform, prefs);
// Exposed for debugging in DevTools.
(window as unknown as { bookReader: AppController }).bookReader = app;

document.documentElement.classList.toggle('platform-mac', platform.isMac);
document.documentElement.dataset.platform = platform.kind;

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <AppContext.Provider value={app}>
      <App />
    </AppContext.Provider>
  </StrictMode>,
);

if (platform.kind === 'web' && 'serviceWorker' in navigator && import.meta.env.PROD) {
  // Offline support + "Install app" for the web build (generated by vite-plugin-pwa).
  void navigator.serviceWorker.register('./sw.js');
}
